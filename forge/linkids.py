"""ID registry and linker (Rule 13): every ID notation links to the note or row that defines it.

ID families are declared in project.toml:

    [ids.D]                      # decisions
    pattern = 'D-\\d{2,3}'
    origin  = '01_Program/Master_Plan.md'      # the table whose first cell defines the ID
    [ids.ADR]
    pattern = 'ADR-\\d{4}'
    files   = '01_Program/Decisions'           # each ID is its own file (ADR-0001_*.md)

V-model IDs (SYS / HWR / SWR / CTL / FW / verification) are linked to their generated notes automatically.
The linker skips frontmatter, headings, code, existing links, URLs and vendor-facing documents
(path contains Vendor_ / Supplier_ / RFQ or frontmatter `audience: external`). Idempotent.

  forge link            dry run (counts)
  forge link --apply    regenerate the registry notes and link the project
"""
import glob
import os
import re
from collections import Counter

LINK = re.compile(r"\[\[([^\]|\\]+)(?:\\?\|([^\]]+))?\]\]")
PROTECT = re.compile(r"(`[^`]*`|\[\[[^\]]*\]\]|!?\[[^\]]*\]\([^)]*\)|https?://\S+|<[^>]+>)")
SKIP = ("/.git/", "/.obsidian/", "/.claude/", "/.forge/", "/_superseded", "/Reviews/", "Vendor_", "Supplier_",
        "/RFQ", "/Literature/", "/Ref_Design/", "/node_modules/")
GEN = "> [!info] Generated by `forge link`. Edit the origin, not this note."


def unlink(s):
    return LINK.sub(lambda m: m.group(2) or m.group(1), s)


def families(prj):
    fam = {}
    for k, v in prj.cfg.get("ids", {}).items():
        fam[k] = dict(v, rx=re.compile(r"^(?:" + v["pattern"] + r")$"))
    return fam


def registry(prj, fam):
    """{id: target note name} and the registry notes to write {path: text}."""
    targets, notes = {}, {}
    reg = prj.p("registry")
    for k, f in fam.items():
        if "files" in f:
            for p in glob.glob(os.path.join(prj.root, f["files"], "**", "*.md"), recursive=True):
                m = re.match(r"(" + f["pattern"] + r")", os.path.basename(p))
                if m:
                    targets[m.group(1)] = os.path.basename(p)[:-3]
            continue
        src = os.path.join(prj.root, f["origin"])
        if not os.path.exists(src):
            continue
        sec = ""
        for line in open(src, errors="ignore"):
            if line.startswith("#"):
                sec = line.strip("# \n")
            if not line.startswith("|"):
                continue
            cells = [c.strip() for c in unlink(line).strip().strip("|").split("|")]
            cid = re.sub(r"[*~]", "", cells[0]).strip()
            if f["rx"].match(cid):
                name = f"{cid}"
                targets[cid] = name
                origin = os.path.basename(src)[:-3]
                notes[os.path.join(reg, k, name + ".md")] = (
                    f"---\ntype: registry\nid: {cid}\nfamily: {k}\norigin: \"[[{origin}#{sec}]]\"\n---\n# {cid}\n\n{GEN}\n\n"
                    f"**Defined in** [[{origin}#{sec}|{origin} § {sec}]]:\n\n> " + " · ".join(c for c in cells[1:] if c) + "\n")
    # V-model notes
    for p in glob.glob(os.path.join(prj.p("vmodel"), "items", "*", "*.md")):
        targets[os.path.basename(p)[:-3]] = os.path.basename(p)[:-3]
    return targets, notes


def md_files(prj):
    for p in glob.glob(os.path.join(prj.root, "**", "*.md"), recursive=True):
        r = "/" + prj.rel(p)
        if any(s in r for s in SKIP) or os.path.basename(p) == "CLAUDE.md" or r.startswith("/" + prj.paths["registry"]):
            continue
        yield p


def link_text(text, targets, any_id, counts):
    out, fm, code = [], False, False
    lines = text.split("\n")
    if lines and lines[0] == "---" and "---" in lines[1:]:
        if any(re.match(r"audience:\s*external", l) for l in lines[1:lines.index("---", 1)]):
            return text
    for i, line in enumerate(lines):
        if i == 0 and line == "---":
            fm = True; out.append(line); continue
        if fm:
            fm = line != "---"; out.append(line); continue
        if line.startswith("```"):
            code = not code
        if code or line.startswith("#"):
            out.append(line); continue
        parts = PROTECT.split(line)
        for j in range(0, len(parts), 2):
            def rep(m):
                t = m.group(1)
                if t not in targets:
                    return t
                counts[t.split("-")[0]] += 1
                return f"[[{t}]]" if targets[t] == t else f"[[{targets[t]}|{t}]]"
            parts[j] = any_id.sub(rep, parts[j])
        out.append("".join(parts))
    return "\n".join(out)


def main(prj, argv):
    fam = families(prj)
    targets, notes = registry(prj, fam)
    if not targets:
        print("no IDs found (declare families in project.toml [ids.*])")
        return 0
    any_id = re.compile(r"(?<![\w/\[\-#.|])(" + "|".join(re.escape(t) for t in sorted(targets, key=len, reverse=True))
                        + r")(?![\w\-\]])")
    counts, changed = Counter(), []
    for p in md_files(prj):
        t = open(p, errors="ignore").read()
        n = link_text(t, targets, any_id, counts)
        if n != t:
            changed.append(p)
            if "--apply" in argv:
                open(p, "w").write(n)
    if "--apply" in argv:
        for p, txt in notes.items():
            os.makedirs(os.path.dirname(p), exist_ok=True)
            if not os.path.exists(p) or open(p).read() != txt:
                open(p, "w").write(txt)
    print(f"{len(targets)} IDs known · {sum(counts.values())} plain mentions {'linked' if '--apply' in argv else 'to link'}"
          f" in {len(changed)} file(s) · {len(notes)} registry notes")
    return 0
