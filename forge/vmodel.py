"""V-model traceability: SYS (L1) -> HWR / SWR / CTL (L2) -> design + FRS (L3) -> verification (L4..L0).

Single sources (edit these, never the generated notes):
  <sys_req>                    L1 system requirements: markdown table rows starting "| SYS-xxx |"
  <vmodel>/trace.csv           L2 derived requirements: id,title,requirement,parents,block,owner,design,frs,verif,method,status,applies,impl,impl_note
  <vmodel>/verification.csv    verification items: id,title,level,procedure,owner,status
  <frs>                        L3 firmware items "| FW-XXX-nn |"

  forge vmodel build | check | impact SYS-... | diff | cr CR-ID [SYS ...] [--why TEXT] | sync
Optional project.toml [vmodel]: section_sv = {"1" = "SV-01"}, l0_all = ["VAL-01"], l0_cert = ["VAL-03"],
compliance_sections = ["9"].
"""
import csv, hashlib, os, re, sys
from collections import defaultdict

LEVEL_NAME = {'L0': 'L0 validation (field / certification)', 'L1': 'L1 system verification',
              'L2': 'L2 integration (HW + FW)', 'L3': 'L3 block verification / analysis',
              'L4': 'L4 unit (code / component)'}
DOMAIN = {'HWR': 'Hardware', 'SWR': 'Software', 'CTL': 'Control'}
GEN = '> [!info] Generated by `forge vmodel build`. Do not edit here: edit {src}, then rebuild.'
PRJ = None


def init(prj):
    global PRJ, ROOT, VM, SR, FRS, TRACE, VER, BASE, ITEMS, CFG, NAME
    PRJ, ROOT, NAME = prj, prj.root, prj.name
    VM, SR, FRS = prj.p('vmodel'), prj.p('sys_req'), prj.p('frs')
    TRACE, VER = os.path.join(VM, 'trace.csv'), os.path.join(VM, 'verification.csv')
    BASE, ITEMS = os.path.join(VM, 'sys_baseline.csv'), os.path.join(VM, 'items')
    CFG = prj.cfg.get('vmodel', {})

UNLINK_RE = re.compile(r'\[\[([^\]|\\]+)(?:\\?\|([^\]]+))?\]\]')


class _U:
    @staticmethod
    def sub(_, s):
        return UNLINK_RE.sub(lambda m: m.group(2) or m.group(1), s)


UNLINK = _U()


def norm(s):
    return re.sub(r'\s+', ' ', s).strip()


def split(s):
    return [x.strip() for x in s.split(';') if x.strip()]


# ---------------------------------------------------------------- parsers
def parse_sys():
    """Return {id: dict(id, aliases, title, text, section, applies, cert)} and alias map."""
    rows, alias, sec = {}, {}, None
    for line in open(SR, encoding='utf-8'):
        m = re.match(r'^#{2,3} (\d+(?:\.\d+)?)\.? ', line)
        if m:
            sec = m.group(1)
        raw = line
        line = UNLINK.sub(None, line)
        if not line.startswith('| SYS-'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        rcells = [c.strip() for c in raw.strip().strip('|').replace('\\|', '\x00').split('|')]
        rcells = [c.replace('\x00', '\\|') for c in rcells]
        if len(rcells) != len(cells):
            rcells = cells
        ids = [x.strip() for x in cells[0].split('/')]
        main = ids[0]
        al = ['SYS-' + x if not x.startswith('SYS-') else x for x in ids[1:]]
        cert = any(re.fullmatch(r'[TAIDC](\s*\+\s*[A-Za-z-]+)*', c) and 'C' in re.split(r'\s*\+\s*', c)
                   for c in cells[1:])
        rows[main] = dict(id=main, aliases=al, title=cells[1] if len(cells) > 1 else '',
                          text=norm(line), cells=rcells, section=sec or '',
                          applies='all', cert=bool(cert))
        alias[main] = main
        for a in al:
            alias[a] = main
    return rows, alias


def parse_frs():
    out = {}
    if not os.path.exists(FRS):
        return out
    for line in open(FRS, encoding='utf-8'):
        line = UNLINK.sub(None, line)
        m = re.match(r'^\| \*{0,2}(FW-[A-Z]+-\d+)\*{0,2} \| (.*)', line)
        if m:
            txt = re.sub(r'\*\*', '', m.group(2).split('|')[0]).strip()
            out[m.group(1)] = txt
    return out


def load_csv(p):
    with open(p, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def doc_index():
    idx = {}
    for d, _, fs in os.walk(ROOT):
        if '/.git' in d or '/_superseded' in d or d.startswith(ITEMS):
            continue
        for f in fs:
            if f.endswith('.md'):
                idx.setdefault(f[:-3], os.path.relpath(os.path.join(d, f), ROOT))
    return idx


class Model:
    def __init__(self, prj=None):
        if prj is not None:
            init(prj)
        self.sys, self.alias = parse_sys()
        self.frs = parse_frs()
        self.tr = load_csv(TRACE)
        self.ver = {v['id']: v for v in load_csv(VER)}
        self.children = defaultdict(list)       # SYS id -> trace rows
        self.frs_users = defaultdict(list)      # FW id -> trace rows
        self.ver_users = defaultdict(list)      # verif id -> trace rows
        for r in self.tr:
            for p in split(r['parents']):
                self.children[self.alias.get(p, p)].append(r)
            for fw in split(r['frs']):
                self.frs_users[fw].append(r)
            for vid in split(r['verif']):
                self.ver_users[vid].append(r)

    def sys_verif(self, s):
        """Verification chain of one SYS row, by level."""
        lv = defaultdict(set)
        for r in self.children[s['id']]:
            for vid in split(r['verif']):
                lv[self.ver.get(vid, {}).get('level', '?')].add(vid)
        sv = CFG.get('section_sv', {}).get(s['section'])
        if sv:
            lv['L1'].add(sv)
        for v in CFG.get('l0_all', []):
            lv['L0'].add(v)
        if s['cert']:
            for v in CFG.get('l0_cert', []):
                lv['L0'].add(v)
        return lv


# ---------------------------------------------------------------- outputs
def link(x):
    return '[[%s]]' % x


def links(xs):
    return ' · '.join(link(x) for x in xs) if xs else '—'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != text:
        open(path, 'w', encoding='utf-8').write(text)


def build(m):
    keep = set()

    def note(sub, name, text):
        p = os.path.join(ITEMS, sub, name + '.md')
        keep.add(p)
        write(p, text)

    # SYS notes
    for s in m.sys.values():
        ch = m.children[s['id']]
        lv = m.sys_verif(s)
        fm = ['---', 'type: req-sys', 'level: L1', 'id: %s' % s['id']]
        if s['aliases']:
            fm.append('aliases: [%s]' % ', '.join(s['aliases']))
        fm += ['section: "§%s"' % s['section'], '---']
        body = ['# %s: %s' % (s['id'], s['title']), '', GEN.format(src='[[System_Requirements]] (CR only)'), '',
                '**Requirement (L1, [[System_Requirements]] §%s):**' % s['section'], '',
                '> ' + ' · '.join(c for c in s['cells'][1:] if c), '',
                '## Derived requirements (L2, left side of the V)', '']
        if ch:
            body += ['| ID | Domain | Title | Owner |', '|---|---|---|---|']
            body += ['| %s | %s | %s | %s |' % (link(r['id']), DOMAIN.get(r['id'].split('-')[0], r['id'].split('-')[0]), r['title'], r['owner']) for r in ch]
        else:
            body.append('_None: verified at system level only (L1 / L0)._')
        body += ['', '## Verification (right side of the V)', '', '| Level | Items |', '|---|---|']
        for L in ['L4', 'L3', 'L2', 'L1', 'L0']:
            if lv.get(L):
                body.append('| %s | %s |' % (LEVEL_NAME[L], links(sorted(lv[L]))))
        note('SYS', s['id'], '\n'.join(fm + body) + '\n')

    # derived notes
    for r in m.tr:
        dom = r['id'].split('-')[0]
        par = [m.alias.get(p, p) for p in split(r['parents'])]
        fws = split(r['frs'])
        vs = split(r['verif'])
        fm = ['---', 'type: req-%s' % dom.lower(), 'level: L2', 'id: %s' % r['id'], 'block: "%s"' % r['block'],
              'status: %s' % r['status'], 'impl: "%s"' % r.get('impl', ''), 'applies: %s' % r['applies'], 'owner: "%s"' % r['owner'],
              'parents: [%s]' % ', '.join('"[[%s]]"' % p for p in par), '---']
        body = ['# %s: %s' % (r['id'], r['title']), '', GEN.format(src='`%s`' % PRJ.rel(TRACE)), '',
                '**%s requirement (L2):** %s' % (DOMAIN.get(dom, dom), r['requirement']), '',
                '| Field | Value |', '|---|---|',
                '| Parents (L1) | %s |' % links(par),
                '| Block | %s |' % r['block'], '| Applies | %s |' % r['applies'], '| Status | %s |' % r['status'],
                '| Owner agent | %s |' % r['owner'],
                '| Design (L3) | %s |' % links(split(r['design'])),
                '| Firmware spec items (L3) | %s |' % (' · '.join(link(f) if f != 'NEW' else '**NEW: to be added to the FRS**' for f in fws) if fws else '—'),
                '| Implementation (L4) | **%s** %s |' % (r.get('impl', '') or '—', ('— ' + r['impl_note']) if r.get('impl_note') else ''),
                '| Method | %s |' % r['method'],
                '| Verification | %s |' % ' · '.join('%s (%s)' % (link(v), m.ver.get(v, {}).get('level', '?')) for v in vs)]
        note(dom, r['id'], '\n'.join(fm + body) + '\n')

    # FRS notes
    for fw, txt in m.frs.items():
        us = m.frs_users.get(fw, [])
        fm = ['---', 'type: fw-item', 'level: L3', 'id: %s' % fw, '---']
        body = ['# %s' % fw, '', GEN.format(src='[[Firmware_Requirements_Spec]]'), '',
                '**Firmware spec item (L3):** %s' % txt[:400], '', 'Source: [[Firmware_Requirements_Spec]]', '',
                '**Implements (L2):** %s' % links([u['id'] for u in us])]
        note('FW', fw, '\n'.join(fm + body) + '\n')

    # verification notes
    sys_by_ver = defaultdict(set)
    for s in m.sys.values():
        for L, vs in m.sys_verif(s).items():
            for v in vs:
                sys_by_ver[v].add(s['id'])
    for vid, v in m.ver.items():
        us = m.ver_users.get(vid, [])
        fm = ['---', 'type: verification', 'level: %s' % v['level'], 'id: %s' % vid, 'status: %s' % v['status'],
              'owner: "%s"' % v['owner'], '---']
        body = ['# %s: %s' % (vid, v['title']), '', GEN.format(src='`%s`' % PRJ.rel(VER)), '',
                '| Field | Value |', '|---|---|', '| Level | %s |' % LEVEL_NAME[v['level']],
                '| Procedure / plan | %s |' % link(v['procedure']), '| Owner | %s |' % v['owner'],
                '| Status | %s |' % v['status'],
                '| Verifies (L2) | %s |' % links([u['id'] for u in us]),
                '| Verifies (L1) | %s |' % links(sorted(sys_by_ver.get(vid, [])))]
        note('VER', vid, '\n'.join(fm + body) + '\n')

    # remove stale notes
    for d, _, fs in os.walk(ITEMS):
        for f in fs:
            p = os.path.join(d, f)
            if p not in keep:
                os.remove(p)

    # domain documents
    for dom, fname, title in [('HWR', 'HW_Requirements', 'Hardware requirements (L2)'),
                              ('SWR', 'SW_Requirements', 'Software requirements (L2)'),
                              ('CTL', 'Control_Requirements', 'Control requirements (L2)')]:
        rows = [r for r in m.tr if r['id'].startswith(dom)]
        out = ['---', 'type: requirement-set', 'title: "%s %s"' % (NAME, title), 'generated: true',
               'source: %s' % PRJ.rel(TRACE), 'parent: "[[System_Requirements]]"', '---',
               '# %s %s' % (NAME, title), '', GEN.format(src='`%s`' % PRJ.rel(TRACE)), '',
               'Derived from [[System_Requirements]] (L1). Process: [[V_Model]]. Every ID opens its own note with backlinks.', '',
               '%d requirements. Status: D = fixed by a decided SYS row, B = baselined, O = open data.' % len(rows), '']
        blk = None
        for r in rows:
            if r['block'] != blk:
                blk = r['block']
                out += ['', '## %s' % blk, '', '| ID | Requirement | Parents (L1) | Design / FRS (L3) | Verification | Owner | Applies | St | Impl (L4) |',
                        '|---|---|---|---|---|---|---|---|---|']
            fws = [f for f in split(r['frs']) if f != 'NEW']
            new = ' · **FRS: NEW**' if 'NEW' in split(r['frs']) else ''
            out.append('| %s | **%s:** %s | %s | %s | %s | %s | %s | %s | **%s**%s |' % (
                link(r['id']), r['title'], r['requirement'], links([m.alias.get(p, p) for p in split(r['parents'])]),
                links(split(r['design']) + fws) + new, links(split(r['verif'])), r['owner'], r['applies'], r['status'],
                r.get('impl', ''), (': ' + r['impl_note']) if r.get('impl_note') else ''))
        write(os.path.join(VM, fname + '.md'), '\n'.join(out) + '\n')

    # verification matrix
    out = ['---', 'type: trace-matrix', 'title: "%s V-model verification matrix"' % NAME, 'generated: true', '---',
           '# Verification matrix: SYS → derived → verification', '', GEN.format(src='the trace sources'), '',
           'One row per system requirement. Left: derived requirements (L2). Right: verification by V level. Process: [[V_Model]].', '']
    cov = sum(1 for s in m.sys.values() if m.children[s['id']])
    out += ['**Coverage:** %d of %d SYS rows have derived requirements; the rest are verified at system level (L1 / L0).' % (cov, len(m.sys)), '']
    sec = None
    for s in m.sys.values():
        if s['section'] != sec:
            sec = s['section']
            out += ['', '## Section %s' % sec, '', '| SYS | Title | HW (L2) | SW (L2) | CTL (L2) | L4 / L3 | L2 | L1 | L0 |', '|---|---|---|---|---|---|---|---|---|']
        ch = m.children[s['id']]
        lv = m.sys_verif(s)
        by = lambda d: links([r['id'] for r in ch if r['id'].startswith(d)])
        out.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            link(s['id']), s['title'], by('HWR'), by('SWR'), by('CTL'),
            links(sorted(lv.get('L4', set()) | lv.get('L3', set()))), links(sorted(lv.get('L2', []))),
            links(sorted(lv.get('L1', []))), links(sorted(lv.get('L0', [])))))
    write(os.path.join(VM, 'Verification_Matrix.md'), '\n'.join(out) + '\n')
    print('built: %d SYS, %d derived, %d FW, %d verification notes' % (len(m.sys), len(m.tr), len(m.frs), len(m.ver)))


# ---------------------------------------------------------------- check
def check(m, quiet=False):
    err, warn = [], []
    say = (lambda *a, **k: None) if quiet else print
    idx = doc_index()
    seen = set()
    for r in m.tr:
        if r['id'] in seen:
            err.append('duplicate id %s' % r['id'])
        seen.add(r['id'])
        for p in split(r['parents']):
            if p not in m.alias:
                err.append('%s: parent %s not in System_Requirements' % (r['id'], p))
        for f in split(r['frs']):
            if f != 'NEW' and f not in m.frs:
                err.append('%s: FRS item %s not found' % (r['id'], f))
        for v in split(r['verif']):
            if v not in m.ver:
                err.append('%s: verification %s not in verification.csv' % (r['id'], v))
        for d in split(r['design']):
            if d not in idx:
                err.append('%s: design doc [[%s]] not found' % (r['id'], d))
        if not split(r['verif']):
            err.append('%s: no verification' % r['id'])
    for v in m.ver.values():
        if v['procedure'] not in idx:
            err.append('%s: procedure [[%s]] not found' % (v['id'], v['procedure']))
    unc = [s for s in m.sys if not m.children[s]]
    new = [r['id'] for r in m.tr if 'NEW' in split(r['frs'])]
    say('SYS rows: %d · derived: %d · verification items: %d' % (len(m.sys), len(m.tr), len(m.ver)))
    say('SYS verified at system level only (no L2 child): %d: %s' % (len(unc), ' '.join(unc)))
    say('L2 items whose FRS item is still NEW (SW agent to add): %d: %s' % (len(new), ' '.join(new)))
    for e in err:
        say('ERROR', e)
    say('%d error(s)' % len(err))
    return 1 if err else 0


# ---------------------------------------------------------------- impact / diff / cr
def impact_lines(m, ids):
    out, agents = [], defaultdict(lambda: defaultdict(set))
    for sid in ids:
        sid = m.alias.get(sid, sid)
        s = m.sys.get(sid)
        if not s:
            out.append('## %s: not found (removed?)' % sid)
            continue
        out += ['## %s: %s' % (link(sid), s['title']), '', '`%s`' % s['text'][:600], '']
        ch = m.children[sid]
        if ch:
            out += ['| Derived (L2) | Owner | Design to revise (L3) | FRS items (L3) | Re-verify |', '|---|---|---|---|---|']
        for r in ch:
            fws = split(r['frs'])
            out.append('| %s %s | %s | %s | %s | %s |' % (link(r['id']), r['title'], r['owner'], links(split(r['design'])),
                       ' · '.join(link(f) if f != 'NEW' else 'NEW' for f in fws) or '—', links(split(r['verif']))))
            for a in [x.strip() for x in r['owner'].split('+')]:
                agents[a]['req'].add(r['id'])
                agents[a]['doc'].update(split(r['design']))
                agents[a]['fw'].update(f for f in fws if f != 'NEW')
        lv = m.sys_verif(s)
        out += ['', '**Verification chain:** ' + ' → '.join('%s %s' % (L, links(sorted(lv[L]))) for L in ['L4', 'L3', 'L2', 'L1', 'L0'] if lv.get(L)), '']
        for L in ['L4', 'L3', 'L2', 'L1', 'L0']:
            for v in lv.get(L, []):
                agents['pe-validation']['ver'].add(v)
        if s['cert'] or s['section'] in CFG.get('compliance_sections', []):
            agents['pe-compliance']['req'].add(sid)
        agents['pe-systems']['req'].add(sid)
    return out, agents


def agent_block(agents):
    out = ['## Work packets per agent', '']
    for a in sorted(agents):
        d = agents[a]
        out.append('### %s' % a)
        if d.get('req'):
            out.append('- Requirements to update / re-check: %s' % links(sorted(d['req'])))
        if d.get('doc'):
            out.append('- Design docs to revise (Rule 5, bump rev): %s' % links(sorted(d['doc'])))
        if d.get('fw'):
            out.append('- FRS items to revise: %s' % links(sorted(d['fw'])))
        if d.get('ver'):
            out.append('- Verification to re-run or re-plan: %s' % links(sorted(d['ver'])))
        out.append('')
    return out


def sys_hash(s):
    return hashlib.sha1(s['text'].encode()).hexdigest()[:12]


def diff(m):
    base = {r['id']: r['hash'] for r in load_csv(BASE)} if os.path.exists(BASE) else {}
    cur = {k: sys_hash(v) for k, v in m.sys.items()}
    changed = [k for k in cur if k in base and base[k] != cur[k]]
    added = [k for k in cur if k not in base]
    removed = [k for k in base if k not in cur]
    return changed, added, removed


def sync(m):
    with open(BASE, 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['id', 'hash'])
        for k, v in m.sys.items():
            w.writerow([k, sys_hash(v)])
    print('baseline synced: %d SYS rows' % len(m.sys))


def main(prj, a):
    if not a:
        print(__doc__)
        return 0
    m = Model(prj)
    cmd = a[0]
    if cmd == 'build':
        build(m)
        from . import linkids
        linkids.main(prj, ['--apply'])
        return 0
    if cmd == 'check':
        return check(m)
    if cmd == 'sync':
        sync(m)
        return 0
    if cmd == 'diff':
        c, ad, rm = diff(m)
        print('changed: %s\nadded: %s\nremoved: %s' % (' '.join(c) or '—', ' '.join(ad) or '—', ' '.join(rm) or '—'))
        if c or ad:
            print('→ run: forge vmodel cr CR-<id> %s --why "..."' % ' '.join(c + ad))
        return 0
    if cmd == 'impact':
        out, ag = impact_lines(m, a[1:])
        print('\n'.join(out + agent_block(ag)))
        return 0
    if cmd == 'cr':
        crid = a[1]
        why = ''
        rest = a[2:]
        if '--why' in rest:
            i = rest.index('--why')
            why = ' '.join(rest[i + 1:])
            rest = rest[:i]
        ids = rest
        if not ids:
            c, ad, rm = diff(m)
            ids = c + ad + rm
        if not ids:
            print('no SYS change found (diff empty); pass SYS ids explicitly')
            return 1
        out, ag = impact_lines(m, ids)
        doc = ['---', 'type: change-request', 'id: %s' % crid, 'status: open', 'sys: [%s]' % ', '.join(ids), '---',
               '# %s: system requirement change packet' % crid, '',
               '**Why:** %s' % (why or '_(fill in)_'), '',
               'Generated by `forge vmodel cr`. Flow ([[V_Model]] §4): systems impact → compliance (Rule 11) → owners revise L2 / L3 → validation re-plans L4…L0 → `forge vmodel build` + `check` → `sync`.', '']
        doc += out + agent_block(ag)
        doc += ['## Close-out checklist', '', '- [ ] [[System_Requirements]] row(s) changed and rev bumped (CR approved by the project owner)',
                '- [ ] `trace.csv` derived rows updated (text, parents, verification)', '- [ ] Design docs / FRS revised (Rule 5) and forge consistency = 0',
                '- [ ] Verification items re-planned in [[DVP_and_R]]', '- [ ] `forge vmodel build` + `check` (0 errors), then `forge vmodel sync`', '']
        p = os.path.join(VM, 'CR', crid + '.md')
        write(p, '\n'.join(doc) + '\n')
        print('wrote', os.path.relpath(p, ROOT))
        return 0
    print(__doc__)
    return 1


